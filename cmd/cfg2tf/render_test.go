func TestRenderValidationFailureAndForce(t *testing.T) {
	t.Parallel()

	// VLAN 1 only, with a PVID pointing at nonexistent VLAN 99.
	config := parseFixture(t,
		vlanSection(4, [2]uint16{1, 0xFFFF}),
		pvidSection(1, 1, 99, 1, 1, 1, 1, 1),
	)

	opts := goldenOptions()
	got, problems := render(config, opts)
	if got != "" {
		t.Fatalf("render() without force returned output, want none")
	}
	if len(problems) == 0 {
		t.Fatal("render() without force returned no problems")
	}
	if !strings.Contains(problems[0].Error(), "does not exist") {
		t.Errorf("render() problem = %v, want a missing-VLAN error", problems[0])
	}

	opts.Force = true
	got, problems = render(config, opts)
	if got == "" {
		t.Fatal("render() with force returned no output")
	}
	if len(problems) == 0 {
		t.Error("render() with force returned no warnings")
	} else if !strings.Contains(problems[0].Error(), "does not exist") {
		t.Errorf("render() warning = %v, want a missing-VLAN warning", problems[0])
	}
	if !strings.Contains(got, `"3" = 99`) {
		t.Error("render() with force must still emit the pvids map")
	}
}

