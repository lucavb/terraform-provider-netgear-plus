func TestRenderGolden(t *testing.T) {
	t.Parallel()

	got, problems := render(goldenConfig(t), goldenOptions())
	if len(problems) != 0 {
		t.Fatalf("render() problems = %v, want none", problems)
	}
	if got != goldenWant {
		t.Fatalf("render() output does not match the golden config.\n--- got ---\n%s\n--- want ---\n%s", got, goldenWant)
	}

	// The golden comparison covers these, but assert the contract
	// explicitly so a golden edit cannot silently drop them.
	for _, want := range []string{
		`data "netgear_plus_switch" "target" {}`,
		"expected_serial_number = data.netgear_plus_switch.target.serial_number",
		`id = "gs108ev3@192.0.2.10"`,
		`"8" = "tagged"`,
		`"3" = "ignored"`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("render() output missing %q", want)
		}
	}

	// Full 8-port coverage in every ports map and in pvids.
	for port := 1; port <= 8; port++ {
		if strings.Count(got, "\""+string(rune('0'+port))+"\" = ") != 3 {
			t.Errorf("render() output does not cover port %d in all 3 maps", port)
		}
	}

	// VLAN blocks sorted ascending.
	if strings.Index(got, "id = 10") < strings.Index(got, "id = 1\n") {
		t.Error("render() output does not sort vlan blocks ascending by id")
	}
}

