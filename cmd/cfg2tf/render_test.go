// All fixtures are assembled synthetically in test code; real backups
// contain password material and must never be used as test input.

const (
	testTag       = 1
	fileHeaderLen = 8
	vlanHeaderLen = 4
	vlanEntryLen  = 4
	sectionHeader = 4
)

// fixture assembles a synthetic FMv2 backup from section records.
func fixture(t *testing.T, sections ...[]byte) []byte {
	t.Helper()

	var payload []byte
	for _, section := range sections {
		payload = append(payload, section...)
	}

	checksum, err := cfg.Checksum(payload)
	if err != nil {
		t.Fatalf("Checksum() error = %v", err)
	}

	data := make([]byte, fileHeaderLen, fileHeaderLen+len(payload))
	copy(data[0:4], "FMv2")
	binary.BigEndian.PutUint16(data[4:6], uint16(len(payload)))
	binary.BigEndian.PutUint16(data[6:8], checksum)

	return append(data, payload...)
}

// writeSection builds one section record: uint16 BE tag, uint16 BE length,
// then name + NUL + data.
func writeSection(name string, data []byte) []byte {
	body := append(append([]byte(name), 0), data...)

	section := make([]byte, sectionHeader, sectionHeader+len(body))
	binary.BigEndian.PutUint16(section[0:2], testTag)
	binary.BigEndian.PutUint16(section[2:4], uint16(len(body)))

	return append(section, body...)
}

// vlanSection builds the vlan section: uint16 LE mode, uint16 LE count, then
// entries of uint16 LE vid + uint16 LE mask (low byte = member bitmap, high
// byte = untagged bitmap).
func vlanSection(mode uint16, entries ...[2]uint16) []byte {
	data := make([]byte, vlanHeaderLen, vlanHeaderLen+len(entries)*vlanEntryLen)
	binary.LittleEndian.PutUint16(data[0:2], mode)
	binary.LittleEndian.PutUint16(data[2:4], uint16(len(entries)))
	for _, entry := range entries {
		var encoded [vlanEntryLen]byte
		binary.LittleEndian.PutUint16(encoded[0:2], entry[0])
		binary.LittleEndian.PutUint16(encoded[2:4], entry[1])
		data = append(data, encoded[:]...)
	}
	return writeSection("vlan", data)
}

// pvidSection builds the pvid section: 16 bytes of 8 uint16 LE values.
func pvidSection(pvids ...int) []byte {
	data := make([]byte, 16)
	for port, pvid := range pvids {
		binary.LittleEndian.PutUint16(data[port*2:], uint16(pvid))
	}
	return writeSection("pvid", data)
}

func parseFixture(t *testing.T, sections ...[]byte) *cfg.Config {
	t.Helper()

	config, err := cfg.ParseConfig(fixture(t, sections...))
	if err != nil {
		t.Fatalf("ParseConfig() error = %v", err)
	}
	return config
}

// goldenConfig decodes two VLANs that exercise every membership value:
// VLAN 1 with untagged ports 1,2,5,6,7 and tagged port 8, and VLAN 10 with
// untagged ports 3,4 and tagged port 8. PVIDs map ports 3,4 to 10 and the
// rest to 1, so the state passes model.VLANState.Validate. The synthetic
// payload checksums to 0x6337.
func goldenConfig(t *testing.T) *cfg.Config {
	t.Helper()

	return parseFixture(t,
		vlanSection(4, [2]uint16{1, 0x73D3}, [2]uint16{10, 0x0C8C}),
		pvidSection(1, 1, 10, 10, 1, 1, 1, 1),
	)
}

func goldenOptions() options {
	return options{
		SourcePath: "test.cfg",
		Host:       "192.0.2.10",
		Model:      "gs108ev3",
		Name:       "switch",
	}
}

// ethSection builds the ethconfig section: 1 mode byte + IPv4 10.0.2.2 +
// netmask 255.255.0.0 + gateway 10.0.0.1, matching the real GS108Ev3
// backup's layout.
func ethSection() []byte {
	return writeSection("ethconfig", []byte{0x01, 0x0A, 0x00, 0x02, 0x02, 0xFF, 0xFF, 0x00, 0x00, 0x0A, 0x00, 0x00, 0x01})
}

// paddingSection returns an unrelated even-length section so the total
// payload stays even, as the format requires.
func paddingSection() []byte {
	return writeSection("misc", []byte{0x00, 0x01})
}

