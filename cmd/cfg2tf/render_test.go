func TestResolveHost(t *testing.T) {
	t.Parallel()

	tests := map[string]struct {
		config      func(t *testing.T) *cfg.Config
		opts        func(t *testing.T) options
		wantHost    string
		wantDerived bool
		wantErr     string
	}{
		"explicit host passes through": {
			config:   goldenConfig,
			opts:     func(t *testing.T) options { return goldenOptions() },
			wantHost: "192.0.2.10",
		},
		"empty host infers from ethconfig": {
			config: func(t *testing.T) *cfg.Config {
				return parseFixture(t,
					vlanSection(4, [2]uint16{1, 0x73D3}, [2]uint16{10, 0x0C8C}),
					pvidSection(1, 1, 10, 10, 1, 1, 1, 1),
					ethSection(),
					paddingSection(),
				)
			},
			opts: func(t *testing.T) options {
				opts := goldenOptions()
				opts.Host = ""
				return opts
			},
			wantHost:    "10.0.2.2",
			wantDerived: true,
		},
		"empty host without ethconfig errors": {
			config: goldenConfig,
			opts: func(t *testing.T) options {
				opts := goldenOptions()
				opts.Host = ""
				return opts
			},
			wantErr: "no -host given and the backup has no usable ethconfig section",
		},
		"empty host with malformed ethconfig errors": {
			config: func(t *testing.T) *cfg.Config {
				return parseFixture(t, writeSection("ethconfig", make([]byte, 12)))
			},
			opts: func(t *testing.T) options {
				opts := goldenOptions()
				opts.Host = ""
				return opts
			},
			wantErr: "no -host given and the backup's ethconfig section is unusable",
		},
	}

	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			resolved, err := resolveHost(test.config(t), test.opts(t))
			if test.wantErr != "" {
				if err == nil {
					t.Fatalf("resolveHost() = %+v, want error containing %q", resolved, test.wantErr)
				}
				if !strings.Contains(err.Error(), test.wantErr) {
					t.Fatalf("resolveHost() error = %v, want error containing %q", err, test.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatalf("resolveHost() error = %v", err)
			}
			if resolved.Host != test.wantHost {
				t.Errorf("resolveHost() Host = %q, want %q", resolved.Host, test.wantHost)
			}
			if resolved.HostInferred != test.wantDerived {
				t.Errorf("resolveHost() HostInferred = %t, want %t", resolved.HostInferred, test.wantDerived)
			}
		})
	}
}

func TestRenderInferredHostComment(t *testing.T) {
	t.Parallel()

	opts := goldenOptions()
	opts.Host = "10.0.2.2"
	opts.HostInferred = true

	got, problems := render(goldenConfig(t), opts)
	if len(problems) != 0 {
		t.Fatalf("render() problems = %v, want none", problems)
	}

	wantHeader := "# Generated by cfg2tf from test.cfg (FMv2 checksum 6337)\n" +
		"# Host 10.0.2.2 was inferred from the backup's ethconfig section; verify it still matches the live switch.\n\n"
	if !strings.HasPrefix(got, wantHeader) {
		t.Fatalf("render() header does not carry the inference comment.\n--- got ---\n%s\n--- want ---\n%s", got, wantHeader)
	}
	if !strings.Contains(got, `host     = "10.0.2.2"`) {
		t.Error(`render() output missing inferred host "10.0.2.2"`)
	}
	if !strings.Contains(got, `id = "gs108ev3@10.0.2.2"`) {
		t.Error(`render() output missing import id "gs108ev3@10.0.2.2"`)
	}
}
